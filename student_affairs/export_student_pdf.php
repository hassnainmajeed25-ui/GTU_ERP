<?php

require_once '../config/config.php';
require_once '../config/database.php';
require_once '../fpdf/fpdf.php';

/*=========================================
LOGIN SECURITY
=========================================*/

if(!isset($_SESSION['admin_id'])){
    header("Location: ../admins/login.php");
    exit;
}

if($_SESSION['department']!="Student Affairs"){
    header("Location: ../admins/login.php");
    exit;
}

/*=========================================
GET STUDENT DATA
=========================================*/

$sql="

SELECT

students.id,
students.registration_no,
students.first_name,
students.last_name,
students.email,
students.mobile,
students.status,

programs.program_name

FROM students

LEFT JOIN applications
ON applications.student_id=students.id

LEFT JOIN programs
ON programs.id=applications.program_id

ORDER BY students.id ASC

";

$result=$conn->query($sql);

/*=========================================
CREATE PDF
=========================================*/

$pdf=new FPDF('L','mm','A4');

$pdf->SetTitle("Student Report");

$pdf->SetAuthor("Global Tech University");

$pdf->AddPage();

$pdf->SetAutoPageBreak(true,15);

/*=========================================
HEADER
=========================================*/

// University Title

$pdf->SetFont('Arial','B',18);

$pdf->Cell(0,10,'GLOBAL TECH UNIVERSITY',0,1,'C');

$pdf->SetFont('Arial','',13);

$pdf->Cell(0,8,'Student Affairs Office',0,1,'C');

$pdf->Cell(0,8,'Student Report',0,1,'C');

$pdf->Ln(5);

// Date & Time

$pdf->SetFont('Arial','',10);

$pdf->Cell(140,8,'Generated Date : '.date("d-m-Y"),0,0);

$pdf->Cell(140,8,'Generated Time : '.date("h:i A"),0,1,'R');

$pdf->Ln(4);

/*=========================================
TABLE HEADER
=========================================*/

$pdf->SetFillColor(11,31,82);

$pdf->SetTextColor(255,255,255);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(12,10,'#',1,0,'C',true);

$pdf->Cell(35,10,'Reg No',1,0,'C',true);

$pdf->Cell(60,10,'Student Name',1,0,'C',true);

$pdf->Cell(55,10,'Program',1,0,'C',true);

$pdf->Cell(70,10,'Email',1,0,'C',true);

$pdf->Cell(35,10,'Mobile',1,0,'C',true);

$pdf->Cell(25,10,'Status',1,1,'C',true);

/*=========================================
TABLE DATA START
=========================================*/

$pdf->SetFont('Arial','',9);

$pdf->SetTextColor(0,0,0);

$sr=1;

/*=========================================
PRINT STUDENT DATA
=========================================*/

if($result && $result->num_rows > 0){

while($row = $result->fetch_assoc()){

    // Registration Number
    if(empty($row['registration_no'])){

        $regNo = "Pending Fee";

    }else{

        $regNo = $row['registration_no'];

    }

    // Program
    if(empty($row['program_name'])){

        $program = "Not Selected";

    }else{

        $program = $row['program_name'];

    }

    // Status Color
    if($row['status']=="Active"){

        $pdf->SetTextColor(0,128,0);

    }else{

        $pdf->SetTextColor(220,53,69);

    }

    $pdf->Cell(12,10,$sr++,1,0,'C');

    $pdf->Cell(35,10,$regNo,1,0,'C');

    $pdf->Cell(
        60,
        10,
        $row['first_name']." ".$row['last_name'],
        1,
        0,
        'L'
    );

    $pdf->Cell(
        55,
        10,
        $program,
        1,
        0,
        'L'
    );

    $pdf->Cell(
        70,
        10,
        $row['email'],
        1,
        0,
        'L'
    );

    $pdf->Cell(
        35,
        10,
        $row['mobile'],
        1,
        0,
        'C'
    );

    $pdf->Cell(
        25,
        10,
        $row['status'],
        1,
        1,
        'C'
    );

    // Reset text color
    $pdf->SetTextColor(0,0,0);

}

}else{

    $pdf->Cell(
        292,
        12,
        'No Student Records Found',
        1,
        1,
        'C'
    );

}

$pdf->Ln(8);

/*=========================================
REPORT SUMMARY
=========================================*/

$totalStudents = $conn->query("SELECT COUNT(*) total FROM students")->fetch_assoc()['total'];

$activeStudents = $conn->query("SELECT COUNT(*) total FROM students WHERE status='Active'")->fetch_assoc()['total'];

$inactiveStudents = $conn->query("SELECT COUNT(*) total FROM students WHERE status='Inactive'")->fetch_assoc()['total'];

$pdf->SetFont('Arial','B',12);

$pdf->Cell(0,8,'Report Summary',0,1);

$pdf->SetFont('Arial','',11);

$pdf->Cell(95,8,'Total Students : '.$totalStudents,1,0);

$pdf->Cell(95,8,'Active Students : '.$activeStudents,1,0);

$pdf->Cell(102,8,'Inactive Students : '.$inactiveStudents,1,1);

$pdf->Ln(10);

/*=========================================
GENERATED BY
=========================================*/

$pdf->SetFont('Arial','',10);

$pdf->Cell(145,8,'Generated By : '.$_SESSION['admin_name'],0,0,'L');

$pdf->Cell(145,8,'Generated On : '.date("d-m-Y h:i A"),0,1,'R');

$pdf->Ln(10);

/*=========================================
SIGNATURES
=========================================*/

$pdf->SetDrawColor(150,150,150);

// Left Signature Line
$pdf->Line(25,$pdf->GetY(),90,$pdf->GetY());

// Right Signature Line
$pdf->Line(205,$pdf->GetY(),270,$pdf->GetY());

$pdf->Ln(3);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(65,6,'Prepared By',0,0,'C');

$pdf->Cell(115);

$pdf->Cell(65,6,'Student Affairs Officer',0,1,'C');

$pdf->Ln(10);

/*=========================================
FOOTER
=========================================*/

$pdf->SetFont('Arial','I',9);

$pdf->SetTextColor(100,100,100);

$pdf->Cell(
0,
6,
'Global Tech University ERP System',
0,
1,
'C'
);

$pdf->Cell(
0,
6,
'Student Affairs Office - Student Report',
0,
1,
'C'
);

$pdf->Cell(
0,
6,
'Generated by GTU ERP | Page '.$pdf->PageNo(),
0,
1,
'C'
);

$pdf->Ln(5);

$pdf->SetFont('Arial','',8);

$pdf->Cell(
0,
5,
'© '.date("Y").' Global Tech University. All Rights Reserved.',
0,
1,
'C'
);

/*=========================================
DOWNLOAD PDF
=========================================*/

$fileName = "Student_Report_".date("Ymd_His").".pdf";

$pdf->Output('D',$fileName);

exit;