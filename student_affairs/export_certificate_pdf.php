<?php

session_start();

require_once '../config/config.php';
require_once '../config/database.php';
require_once '../fpdf/fpdf.php';

/*=========================================
LOGIN SECURITY
=========================================*/

if(!isset($_SESSION['admin_id'])){

    header("Location: ../admins/login.php");
    exit;

}

if($_SESSION['department']!="Student Affairs"){

    header("Location: ../admins/login.php");
    exit;

}

/*=========================================
GET CERTIFICATE REQUESTS
=========================================*/

$sql="

SELECT

certificate_requests.request_no,
certificate_requests.certificate_type,
certificate_requests.status,
certificate_requests.created_at,

students.first_name,
students.last_name

FROM certificate_requests

LEFT JOIN students

ON students.id = certificate_requests.student_id

ORDER BY certificate_requests.id ASC

";

$result = $conn->query($sql);

/*=========================================
CREATE PDF
=========================================*/

$pdf = new FPDF('P','mm','A4');

$pdf->SetTitle("Certificate Report");

$pdf->SetAuthor("Global Tech University");

$pdf->SetCreator("GTU ERP");

$pdf->AddPage();

$pdf->SetAutoPageBreak(true,15);

/*=========================================
HEADER
=========================================*/

$pdf->SetFont('Arial','B',18);

$pdf->Cell(190,10,'GLOBAL TECH UNIVERSITY',0,1,'C');

$pdf->SetFont('Arial','',12);

$pdf->Cell(190,8,'Student Affairs Office',0,1,'C');

$pdf->Cell(190,8,'Certificate Requests Report',0,1,'C');

$pdf->Ln(5);

$pdf->SetFont('Arial','',10);

$pdf->Cell(95,8,'Generated Date : '.date("d-m-Y"),0,0);

$pdf->Cell(95,8,'Generated Time : '.date("h:i A"),0,1,'R');

$pdf->Ln(5);

/*=========================================
TABLE HEADER
=========================================*/

$pdf->SetFillColor(11,31,82);

$pdf->SetTextColor(255,255,255);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(10,10,'#',1,0,'C',true);

$pdf->Cell(35,10,'Request No',1,0,'C',true);

$pdf->Cell(55,10,'Student Name',1,0,'C',true);

$pdf->Cell(40,10,'Certificate',1,0,'C',true);

$pdf->Cell(25,10,'Status',1,0,'C',true);

$pdf->Cell(25,10,'Date',1,1,'C',true);

/*=========================================
TABLE DATA
=========================================*/

$pdf->SetFont('Arial','',9);

$pdf->SetTextColor(0,0,0);

$sr=1;

/*=========================================
PRINT TABLE DATA
=========================================*/

if($result && $result->num_rows > 0){

while($row = $result->fetch_assoc()){

    // Status Color
    if($row['status']=="Approved"){

        $pdf->SetTextColor(0,128,0);

    }elseif($row['status']=="Rejected"){

        $pdf->SetTextColor(220,53,69);

    }elseif($row['status']=="Pending"){

        $pdf->SetTextColor(255,140,0);

    }else{

        $pdf->SetTextColor(0,0,0);

    }

    $pdf->Cell(10,10,$sr++,1,0,'C');

    $pdf->Cell(35,10,$row['request_no'],1,0,'C');

    $pdf->Cell(55,10,

        $row['first_name']." ".$row['last_name'],

        1,0,'L');

    $pdf->Cell(40,10,

        $row['certificate_type'],

        1,0,'L');

    $pdf->Cell(25,10,

        $row['status'],

        1,0,'C');

    $pdf->Cell(25,10,

        date("d-m-Y",

        strtotime($row['created_at'])),

        1,1,'C');

    // Next Row Black Color
    $pdf->SetTextColor(0,0,0);

}

}else{

$pdf->Cell(

190,

12,

'No Certificate Requests Found',

1,

1,

'C'

);

}

$pdf->Ln(10);

/*=========================================
SUMMARY
=========================================*/

$total=$conn->query("SELECT COUNT(*) total FROM certificate_requests")->fetch_assoc()['total'];

$approved=$conn->query("SELECT COUNT(*) total FROM certificate_requests WHERE status='Approved'")->fetch_assoc()['total'];

$pending=$conn->query("SELECT COUNT(*) total FROM certificate_requests WHERE status='Pending'")->fetch_assoc()['total'];

$rejected=$conn->query("SELECT COUNT(*) total FROM certificate_requests WHERE status='Rejected'")->fetch_assoc()['total'];

$pdf->SetFont('Arial','B',12);

$pdf->Cell(190,10,'Report Summary',0,1);

$pdf->SetFont('Arial','',11);

$pdf->Cell(95,8,'Total Requests : '.$total,1,0);

$pdf->Cell(95,8,'Approved : '.$approved,1,1);

$pdf->Cell(95,8,'Pending : '.$pending,1,0);

$pdf->Cell(95,8,'Rejected : '.$rejected,1,1);

$pdf->Ln(12);
/*=========================================
FOOTER
=========================================*/

$pdf->SetY(-45);

$pdf->SetFont('Arial','I',9);

$pdf->Cell(190,6,'Generated By : '.$_SESSION['admin_name'],0,1,'L');

$pdf->Cell(190,6,'Generated On : '.date("d-m-Y h:i A"),0,1,'L');

$pdf->Ln(5);

$pdf->SetDrawColor(180,180,180);

$pdf->Line(20,$pdf->GetY(),80,$pdf->GetY());

$pdf->Line(130,$pdf->GetY(),190,$pdf->GetY());

$pdf->Ln(2);

$pdf->Cell(60,6,'Prepared By',0,0,'C');

$pdf->Cell(70);

$pdf->Cell(60,6,'Student Affairs Officer',0,1,'C');

$pdf->Ln(8);

$pdf->SetFont('Arial','I',8);

$pdf->SetTextColor(120,120,120);

$pdf->Cell(

190,

5,

'Global Tech University ERP System | Certificate Report',

0,

1,

'C'

);

$pdf->Cell(

190,

5,

'Page '.$pdf->PageNo(),

0,

1,

'C'

);

/*=========================================
DOWNLOAD PDF
=========================================*/

$fileName = "Certificate_Report_".date("Ymd_His").".pdf";

$pdf->Output('D',$fileName);

exit;

?>