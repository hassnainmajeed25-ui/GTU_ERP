<?php

require_once '../config/config.php';
require_once '../config/database.php';
require_once '../fpdf/fpdf.php';

/*=========================================
LOGIN SECURITY
=========================================*/

if(!isset($_SESSION['admin_id'])){
    header("Location: ../admins/login.php");
    exit;
}

if($_SESSION['department']!="Student Affairs"){
    header("Location: ../admins/login.php");
    exit;
}

/*=========================================
GET COMPLAINTS
=========================================*/

$sql="

SELECT

complaints.id,
complaints.subject,
complaints.message,
complaints.status,
complaints.created_at,

students.first_name,
students.last_name

FROM complaints

LEFT JOIN students

ON students.id = complaints.student_id

ORDER BY complaints.id ASC

";

$result = $conn->query($sql);

/*=========================================
CREATE PDF
=========================================*/

$pdf = new FPDF('L','mm','A4');

$pdf->SetTitle("Complaint Report");

$pdf->SetAuthor("Global Tech University");

$pdf->SetCreator("GTU ERP");

$pdf->AddPage();

$pdf->SetAutoPageBreak(true,15);

/*=========================================
HEADER
=========================================*/

$pdf->SetFont('Arial','B',18);

$pdf->Cell(0,10,'GLOBAL TECH UNIVERSITY',0,1,'C');

$pdf->SetFont('Arial','',13);

$pdf->Cell(0,8,'Student Affairs Office',0,1,'C');

$pdf->Cell(0,8,'Complaint Report',0,1,'C');

$pdf->Ln(4);

$pdf->SetFont('Arial','',10);

$pdf->Cell(140,8,'Generated Date : '.date("d-m-Y"),0,0);

$pdf->Cell(140,8,'Generated Time : '.date("h:i A"),0,1,'R');

$pdf->Ln(5);

/*=========================================
TABLE HEADER
=========================================*/

$pdf->SetFillColor(11,31,82);

$pdf->SetTextColor(255,255,255);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(12,10,'#',1,0,'C',true);

$pdf->Cell(55,10,'Student Name',1,0,'C',true);

$pdf->Cell(55,10,'Subject',1,0,'C',true);

$pdf->Cell(95,10,'Complaint',1,0,'C',true);

$pdf->Cell(30,10,'Status',1,0,'C',true);

$pdf->Cell(35,10,'Date',1,1,'C',true);

/*=========================================
TABLE DATA
=========================================*/

$pdf->SetFont('Arial','',9);

$pdf->SetTextColor(0,0,0);

$sr=1;

if($result && $result->num_rows>0){

while($row=$result->fetch_assoc()){

    // Status Color

    if($row['status']=="Resolved"){

        $pdf->SetTextColor(0,128,0);

    }

    elseif($row['status']=="Pending"){

        $pdf->SetTextColor(255,140,0);

    }

    elseif($row['status']=="Rejected"){

        $pdf->SetTextColor(220,53,69);

    }

    else{

        $pdf->SetTextColor(0,0,255);

    }

    // Complaint Message Short

    $message=$row['message'];

    if(strlen($message)>50){

        $message=substr($message,0,50).'...';

    }

    $pdf->Cell(12,10,$sr++,1,0,'C');

    $pdf->Cell(

        55,

        10,

        $row['first_name']." ".$row['last_name'],

        1,

        0,

        'L'

    );

    $pdf->Cell(

        55,

        10,

        $row['subject'],

        1,

        0,

        'L'

    );

    $pdf->Cell(

        95,

        10,

        $message,

        1,

        0,

        'L'

    );

    $pdf->Cell(

        30,

        10,

        $row['status'],

        1,

        0,

        'C'

    );

    $pdf->Cell(

        35,

        10,

        date("d-m-Y",strtotime($row['created_at'])),

        1,

        1,

        'C'

    );

    // Reset Color

    $pdf->SetTextColor(0,0,0);

}

}else{

    $pdf->Cell(

        282,

        12,

        'No Complaint Records Found',

        1,

        1,

        'C'

    );

}

$pdf->Ln(8);

/*=========================================
REPORT SUMMARY
=========================================*/

$total = $conn->query("SELECT COUNT(*) total FROM complaints")->fetch_assoc()['total'];

$pending = $conn->query("SELECT COUNT(*) total FROM complaints WHERE status='Pending'")->fetch_assoc()['total'];

$resolved = $conn->query("SELECT COUNT(*) total FROM complaints WHERE status='Resolved'")->fetch_assoc()['total'];

$rejected = $conn->query("SELECT COUNT(*) total FROM complaints WHERE status='Rejected'")->fetch_assoc()['total'];

$pdf->SetFont('Arial','B',12);

$pdf->Cell(0,8,'Complaint Report Summary',0,1);

$pdf->SetFont('Arial','',11);

$pdf->Cell(70,8,'Total : '.$total,1,0);

$pdf->Cell(70,8,'Pending : '.$pending,1,0);

$pdf->Cell(70,8,'Resolved : '.$resolved,1,0);

$pdf->Cell(72,8,'Rejected : '.$rejected,1,1);

$pdf->Ln(10);

/*=========================================
GENERATED BY
=========================================*/

$pdf->SetFont('Arial','',10);

$pdf->Cell(
140,
8,
'Generated By : '.$_SESSION['admin_name'],
0,
0,
'L'
);

$pdf->Cell(
140,
8,
'Generated On : '.date("d-m-Y h:i A"),
0,
1,
'R'
);

$pdf->Ln(8);

/*=========================================
SIGNATURE SECTION
=========================================*/

$pdf->SetDrawColor(160,160,160);

// Left Signature

$pdf->Line(20,$pdf->GetY(),90,$pdf->GetY());

// Right Signature

$pdf->Line(205,$pdf->GetY(),275,$pdf->GetY());

$pdf->Ln(3);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(
70,
6,
'Prepared By',
0,
0,
'C'
);

$pdf->Cell(135);

$pdf->Cell(
70,
6,
'Student Affairs Officer',
0,
1,
'C'
);

$pdf->Ln(10);

/*=========================================
SYSTEM INFORMATION
=========================================*/

$pdf->SetFont('Arial','B',11);

$pdf->Cell(
0,
8,
'Global Tech University ERP System',
0,
1,
'C'
);

$pdf->SetFont('Arial','',10);

$pdf->Cell(
0,
6,
'Student Affairs Department',
0,
1,
'C'
);

$pdf->Cell(
0,
6,
'Complaint Management Report',
0,
1,
'C'
);

$pdf->Ln(5);

/*=========================================
DISCLAIMER
=========================================*/

$pdf->SetFont('Arial','I',8);

$pdf->SetTextColor(100,100,100);

$pdf->MultiCell(
0,
5,
'This report is generated automatically by the Global Tech University ERP System. '
.'The information contained in this report is confidential and intended for official '
.'administrative use only. Unauthorized copying, editing or distribution is prohibited.',
0,
'C'
);

$pdf->Ln(5);

/*=========================================
FOOTER
=========================================*/

$pdf->SetFont('Arial','I',8);

$pdf->Cell(
0,
5,
'Page '.$pdf->PageNo(),
0,
1,
'C'
);

$pdf->Cell(
0,
5,
'Generated on '.date("d-m-Y h:i A"),
0,
1,
'C'
);

$pdf->Cell(
0,
5,
'© '.date("Y").' Global Tech University ERP System. All Rights Reserved.',
0,
1,
'C'
);

/*=========================================
DOWNLOAD PDF
=========================================*/

$fileName="Complaint_Report_".date("Ymd_His").".pdf";

$pdf->Output("D",$fileName);

exit;

