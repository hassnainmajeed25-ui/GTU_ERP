<?php

require_once '../config/config.php';
require_once '../config/database.php';
require_once '../fpdf/fpdf.php';

/*=========================================
LOGIN SECURITY
=========================================*/

if(!isset($_SESSION['admin_id'])){
    header("Location: ../admins/login.php");
    exit;
}

if($_SESSION['department']!="Student Affairs"){
    header("Location: ../admins/login.php");
    exit;
}

/*=========================================
GET MESSAGES
=========================================*/

$sql="

SELECT *

FROM messages

ORDER BY id DESC

";

$result=$conn->query($sql);

/*=========================================
CREATE PDF
=========================================*/

$pdf=new FPDF('L','mm','A4');

$pdf->SetTitle("Message Report");

$pdf->SetAuthor("Global Tech University");

$pdf->SetCreator("GTU ERP");

$pdf->AddPage();

$pdf->SetAutoPageBreak(true,15);

/*=========================================
HEADER
=========================================*/

$pdf->SetFont('Arial','B',18);

$pdf->Cell(0,10,'GLOBAL TECH UNIVERSITY',0,1,'C');

$pdf->SetFont('Arial','',13);

$pdf->Cell(0,8,'Student Affairs Office',0,1,'C');

$pdf->Cell(0,8,'Message Report',0,1,'C');

$pdf->Ln(5);

$pdf->SetFont('Arial','',10);

$pdf->Cell(140,8,'Generated Date : '.date("d-m-Y"),0,0);

$pdf->Cell(140,8,'Generated Time : '.date("h:i A"),0,1,'R');

$pdf->Ln(5);

/*=========================================
TABLE HEADER
=========================================*/

$pdf->SetFillColor(11,31,82);

$pdf->SetTextColor(255,255,255);

$pdf->SetFont('Arial','B',9);

$pdf->Cell(10,10,'#',1,0,'C',true);

$pdf->Cell(30,10,'Sender',1,0,'C',true);

$pdf->Cell(30,10,'Receiver',1,0,'C',true);

$pdf->Cell(55,10,'Subject',1,0,'C',true);

$pdf->Cell(110,10,'Message',1,0,'C',true);

$pdf->Cell(20,10,'Status',1,0,'C',true);

$pdf->Cell(35,10,'Date',1,1,'C',true);

/*=========================================
TABLE DATA
=========================================*/

$pdf->SetFont('Arial','',8);

$pdf->SetTextColor(0,0,0);

$sr=1;

/*=========================================
PRINT MESSAGE RECORDS
=========================================*/

if($result && $result->num_rows>0){

while($row=$result->fetch_assoc()){

    $subject=$row['subject'];

    if(strlen($subject)>30){
        $subject=substr($subject,0,30).'...';
    }

    $message=$row['message'];

    if(strlen($message)>65){
        $message=substr($message,0,65).'...';
    }

    if($row['is_read']==1){
        $status="Read";
        $pdf->SetTextColor(0,128,0);
    }else{
        $status="Unread";
        $pdf->SetTextColor(220,53,69);
    }

    $pdf->Cell(10,10,$sr++,1,0,'C');

    $pdf->Cell(
        30,
        10,
        $row['sender_role'],
        1,
        0,
        'C'
    );

    $pdf->Cell(
        30,
        10,
        $row['receiver_role'],
        1,
        0,
        'C'
    );

    $pdf->Cell(
        55,
        10,
        $subject,
        1,
        0,
        'L'
    );

    $pdf->Cell(
        110,
        10,
        $message,
        1,
        0,
        'L'
    );

    $pdf->Cell(
        20,
        10,
        $status,
        1,
        0,
        'C'
    );

    $pdf->Cell(
        35,
        10,
        date("d-m-Y",strtotime($row['created_at'])),
        1,
        1,
        'C'
    );

    $pdf->SetTextColor(0,0,0);

}

}else{

    $pdf->Cell(
        290,
        12,
        'No Message Records Found',
        1,
        1,
        'C'
    );

}

$pdf->Ln(8);

/*=========================================
REPORT SUMMARY
=========================================*/

$total=$conn->query("
SELECT COUNT(*) total
FROM messages
")->fetch_assoc()['total'];

$read=$conn->query("
SELECT COUNT(*) total
FROM messages
WHERE is_read=1
")->fetch_assoc()['total'];

$unread=$conn->query("
SELECT COUNT(*) total
FROM messages
WHERE is_read=0
")->fetch_assoc()['total'];

$pdf->SetFont('Arial','B',12);

$pdf->Cell(0,8,'Message Report Summary',0,1);

$pdf->SetFont('Arial','',11);

$pdf->Cell(95,8,'Total Messages : '.$total,1,0);

$pdf->Cell(95,8,'Read : '.$read,1,0);

$pdf->Cell(100,8,'Unread : '.$unread,1,1);

$pdf->Ln(10);

/*=========================================
GENERATED BY
=========================================*/

$pdf->SetFont('Arial','',10);

$pdf->Cell(
145,
8,
'Generated By : '.$_SESSION['admin_name'],
0,
0,
'L'
);

$pdf->Cell(
145,
8,
'Generated On : '.date("d-m-Y h:i A"),
0,
1,
'R'
);

$pdf->Ln(10);

/*=========================================
SIGNATURE
=========================================*/

$pdf->Line(25,$pdf->GetY(),90,$pdf->GetY());

$pdf->Line(205,$pdf->GetY(),270,$pdf->GetY());

$pdf->Ln(3);

$pdf->SetFont('Arial','B',10);

$pdf->Cell(65,6,'Prepared By',0,0,'C');

$pdf->Cell(115);

$pdf->Cell(65,6,'Student Affairs Officer',0,1,'C');

$pdf->Ln(10);

/*=========================================
FOOTER
=========================================*/

$pdf->SetFont('Arial','I',9);

$pdf->SetTextColor(100,100,100);

$pdf->Cell(
0,
6,
'Global Tech University ERP System',
0,
1,
'C'
);

$pdf->Cell(
0,
6,
'Student Affairs Office - Message Report',
0,
1,
'C'
);

$pdf->Cell(
0,
6,
'Generated by GTU ERP | Page '.$pdf->PageNo(),
0,
1,
'C'
);

$pdf->Ln(5);

$pdf->SetFont('Arial','',8);

$pdf->Cell(
0,
5,
'© '.date("Y").' Global Tech University. All Rights Reserved.',
0,
1,
'C'
);

/*=========================================
DOWNLOAD PDF
=========================================*/

$fileName="Message_Report_".date("Ymd_His").".pdf";

$pdf->Output("D",$fileName);

exit;

?>